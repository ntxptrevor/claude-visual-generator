#!/usr/bin/env python3
"""Render docs/ADMIN_RUNBOOK.md from admin_console/runbook_seed.json.

The JSON is the source of truth (the server seeds /api/runbook from it). Edit the JSON,
then run:  python3 admin_console/tools/render_runbook.py
Use --check in CI to fail when the markdown is stale.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SEED = ROOT / "admin_console" / "runbook_seed.json"
OUT = ROOT / "docs" / "ADMIN_RUNBOOK.md"
FIELDS = ("id", "workflow", "symptom", "likely_cause", "steps", "escalate_to", "tier", "updated")
TIER_TEXT = {0: "0 - look only, no change", 1: "1 - routine, batch OK",
             2: "2 - tell the owners, then act", 3: "3 - explain and wait for owner approval"}

HEADER = """# NTXP Admin Runbook

> Generated from `admin_console/runbook_seed.json` by `admin_console/tools/render_runbook.py`.
> Do not edit this file by hand. Edit the JSON (or add entries in the console's Runbook
> page) and re-run the script.

**Who this is for:** the NTXP office admin, or anyone, when a workflow is stuck.

**How to use it**
- **Find** your symptom below (or search the Runbook page at https://admin.ntxpllc.com).
- **Follow** the steps in order. Stop at any step that needs access you do not have.
- **Escalate** to the person named on the entry if the steps do not fix it.
- **Never** paste passwords, keys or tokens into chat, email, tickets or this runbook.

**Who to escalate to**
- **Trevor Hopkins (operations):** tools, logins, deploys, data sources, process.
- **Alison Hopkins (owner):** money, legal, HR/personnel, signatures, security incidents, policy.

**Tier** is the NTXP change-gate tier of the fix:
- **0:** look only, no change.
- **1:** routine; can be batched under one "ok".
- **2:** tell the owners what will change, then act unless they object.
- **3:** explain exactly what will change and wait for owner approval.
"""


def slug(text):
    """GitHub-style heading anchor."""
    text = text.strip().lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def load():
    entries = json.loads(SEED.read_text(encoding="utf-8"))
    ids = set()
    for e in entries:
        missing = [f for f in FIELDS if f not in e]
        if missing:
            sys.exit(f"{e.get('id', '?')}: missing {missing}")
        if e["id"] in ids:
            sys.exit(f"duplicate id {e['id']}")
        ids.add(e["id"])
    return entries


def render(entries):
    groups = {}
    for e in entries:
        groups.setdefault(e["workflow"], []).append(e)

    lines = [HEADER, f"**Entries:** {len(entries)} across {len(groups)} workflows.\n",
             "## Contents\n"]
    for wf, items in groups.items():
        lines.append(f"- [{wf}](#{slug(wf)}) ({len(items)})")
        for e in items:
            title = f"{e['id']} {e['symptom']}"
            short = e["symptom"] if len(e["symptom"]) <= 90 else e["symptom"][:87].rstrip() + "..."
            lines.append(f"  - [{e['id']}](#{slug(title)}) {short}")
    lines.append("")

    for wf, items in groups.items():
        lines += ["---", "", f"## {wf}", ""]
        for e in items:
            lines += [f"### {e['id']} {e['symptom']}", "",
                      f"- **Likely cause:** {e['likely_cause']}",
                      f"- **Escalate to:** {e['escalate_to']}",
                      f"- **Tier:** {TIER_TEXT.get(e['tier'], e['tier'])}",
                      f"- **Updated:** {e['updated']}", "", "**Steps**", ""]
            lines += [f"{i}. {s}" for i, s in enumerate(e["steps"], 1)]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the markdown is stale")
    args = ap.parse_args()
    text = render(load())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            sys.exit("docs/ADMIN_RUNBOOK.md is stale; run admin_console/tools/render_runbook.py")
        print("runbook up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10) + '### ')} entries)")


if __name__ == "__main__":
    main()
